test('document draft journal protects failed saves and restart, commits idempotently and retains conflicts', async () => {
  const { root, db, docs } = setup();
  const registered = await docs.request({ action: 'register', entries: [{ reference: 'https://example.com/Manual' }], context: null }) as DocumentBatch;
  const doc = docs.get(registered.registered[0]!);
  const journal = new DocumentDraftJournal(join(root, 'drafts', 'documents'));
  const actions = new DocumentActions(docs, { pick: async () => [], openPath: async () => '', openExternal: async () => {} }, journal);
  const draft = { token: randomUUID(), edit: { action: 'edit' as const, id: doc.id, revision: doc.revision, name: '下書きマニュアル', reference: doc.reference, kind: doc.kind, description: '保存できなくても保持' } };
  assert.ok((await actions.request({ action: 'stage-edit', draft })).ok);
  db.db.exec('PRAGMA query_only=ON'); assert.equal((await actions.request({ action: 'commit-edit', draft })).ok, false); assert.equal(journal.list()[0]!.edit.action, 'edit');
  db.db.exec('PRAGMA query_only=OFF'); db.close();
  const reopened = new WorkspaceDatabase(join(root, 'workspace.sqlite')), repo = new DocumentRepository(reopened);
  const next = new DocumentActions(repo, { pick: async () => [], openPath: async () => '', openExternal: async () => {} }, new DocumentDraftJournal(join(root, 'drafts', 'documents')));
  const recovery = await next.request({ action: 'list' }); assert.ok(recovery.ok); if (recovery.ok) assert.equal((recovery.value as { drafts: unknown[] }).drafts.length, 1);
  assert.ok((await next.request({ action: 'commit-edit', draft })).ok); assert.ok((await next.request({ action: 'commit-edit', draft })).ok);
  assert.equal(repo.get(doc.id).revision, 2); assert.equal(repo.get(doc.id).name, '下書きマニュアル'); assert.equal(journal.list().length, 0);
  const stale = { ...draft, token: randomUUID() }; await next.request({ action: 'stage-edit', draft: stale }); assert.equal((await next.request({ action: 'commit-edit', draft: stale })).ok, false); assert.equal(journal.list().length, 1);
  await next.request({ action: 'discard-edit', draft: stale }); assert.equal(journal.list().length, 0);
  reopened.close();
});
test('reordering validates the complete context and revisions, rolls back failures and preserves memo fields', async () => {
  const {db,docs,a,b}=setup();
  const batch=await docs.request({action:'register',entries:[{reference:'https://example.com/a'},{reference:'https://example.com/b'}],context:{kind:'item',id:a.id}}) as DocumentBatch;
  const [first,second]=batch.registered as [string,string];
  const context={kind:'item' as const,id:a.id};
  const before=docs.snapshot().uses;
  const request={action:'reorder',context,ids:[second,first],revisions:[1,1]};
  await assert.rejects(docs.request({...request,ids:[first,first]}));
  await assert.rejects(docs.request({...request,context:{kind:'item',id:b.id}}));
  db.db.exec(`CREATE TRIGGER fail_order BEFORE UPDATE ON document_uses WHEN old.documentId='${first}' BEGIN SELECT RAISE(ABORT,'injected failure'); END;`);
  await assert.rejects(docs.request(request));assert.deepEqual(docs.snapshot().uses,before);
  db.db.exec('DROP TRIGGER fail_order');await docs.request(request);
  assert.deepEqual(docs.snapshot().uses.map(use=>use.documentId),[second,first]);
  assert.deepEqual(docs.snapshot().uses.map(use=>[use.memo,use.group]),[['',''],['','']]);
  await assert.rejects(docs.request(request));
  db.close();
});
