test('theme order includes page-only documents, persists independently and rejects stale membership without changing uses',async()=>{
  const {db,docs,theme,a,b,root}=setup();
  const direct={kind:'theme' as const,id:theme.id},page={kind:'item' as const,id:a.id};
  const register=async(reference:string,context:typeof direct|typeof page)=>(await docs.request({action:'register',entries:[{reference}],context}) as DocumentBatch).registered[0]!;
  const x=await register('https://example.com/direct',direct),y=await register('https://example.com/page',page),z=await register('https://example.com/other',{kind:'item',id:b.id});
  const before=docs.snapshot().uses;
  const revisions=(ids:string[])=>ids.map(id=>before.find(u=>u.documentId===id)!.revision);
  await docs.request({action:'reorder',context:direct,ids:[z,x,y],revisions:revisions([z,x,y])});
  assert.deepEqual(docs.snapshot().themeOrders?.[theme.id],[z,x,y]);assert.deepEqual(docs.snapshot().uses,before);
  await assert.rejects(docs.request({action:'reorder',context:direct,ids:[x,y],revisions:revisions([x,y])}));
  assert.deepEqual(docs.snapshot().themeOrders?.[theme.id],[z,x,y]);
  db.close();const reopened=new WorkspaceDatabase(join(root,'workspace.sqlite'));assert.deepEqual(new DocumentRepository(reopened).snapshot().themeOrders?.[theme.id],[z,x,y]);reopened.close();
});
test('document references distinguish Windows paths and URL case; reject unsafe schemes and namespace paths', () => {
  assert.equal(normalizeReference('"C:/Lab/../Lab/Manual.pdf"').normalized, normalizeReference('c:\\lab\\manual.pdf').normalized);
  assert.equal(normalizeReference('file:///C:/Lab/Manual.pdf').normalized, normalizeReference('C:\\Lab\\Manual.pdf').normalized);
  assert.equal(normalizeReference('HTTPS://EXAMPLE.COM:443/Manual?Key=A').reference, 'https://example.com/Manual?Key=A');
  assert.notEqual(normalizeReference('https://example.com/Manual').normalized, normalizeReference('https://example.com/manual').normalized);
  assert.equal(normalizeReference('\\\\server\\share\\folder\\', 'folder').kind, 'folder');
  for (const value of ['javascript:alert(1)', 'data:text/plain,a', 'shell:Downloads', 'relative.txt', 'C:relative.txt', '\\\\?\\C:\\file', 'C:\\file:stream', 'https://user:password@example.com/', 'C:\\file\0.txt']) assert.throws(() => normalizeReference(value));
});
test('batch partial retry, reference reuse, same names and context isolation survive restart; originals remain byte identical', async () => {
  const { root, db, docs, theme, a, b } = setup();
  mkdirSync(join(root, 'one')); mkdirSync(join(root, 'two'));
  const original = join(root, 'one', 'manual.txt'), other = join(root, 'two', 'manual.txt');
  writeFileSync(original, 'original content 日本語'); writeFileSync(other, 'other original'); const before = readFileSync(original);
  const batch = await docs.request({ action: 'register', entries: [{ reference: original }, { reference: other }, { reference: 'javascript:bad' }], context: { kind: 'item', id: a.id } }) as DocumentBatch;
  assert.equal(batch.registered.length, 2); assert.equal(batch.failed.length, 1);
  const id = batch.registered[0]!;
  const retry = await docs.request({ action: 'register', entries: [{ reference: original.toUpperCase() }, { reference: 'https://example.com/Manual' }], context: { kind: 'item', id: b.id } }) as DocumentBatch;
  assert.equal(retry.registered[0], id); assert.equal(docs.snapshot().documents.length, 3);
  await docs.request({ action: 'attach', id, context: { kind: 'theme', id: theme.id } });
  const use = docs.snapshot().uses.find(use => use.documentId === id && use.contextId === a.id)!;
  await docs.request({ action: 'use', id, context: { kind: 'item', id: a.id }, revision: use.revision, memo: '装置準備で使う', group: '手順・準備', position: 4 });
  assert.equal(docs.snapshot().uses.find(use => use.documentId === id && use.contextId === b.id)!.memo, '');
  assert.equal(new Set(documentUses(docs.snapshot(), { kind: 'theme', id: theme.id }, db.items()).map(use => use.documentId)).size, 3);
  const doc = docs.get(id);
  await docs.request({ action: 'edit', id, revision: doc.revision, name: '共通マニュアル', reference: original, description: '説明', kind: 'file' });
  assert.equal(docs.snapshot().uses.filter(use => use.documentId === id).length, 3);
  assert.deepEqual(readFileSync(original), before);
  await assert.rejects(docs.request({ action: 'edit', id, revision: doc.revision, name: '古い編集', reference: original, description: '', kind: 'file' }));
  await assert.rejects(docs.request({ action: 'remove', id, revision: docs.get(id).revision, linkCount: 1 }));
  const view = { query: '校正', kind: 'file', theme: theme.id, sort: 'name-desc', scroll: 240, selected: id };
  await docs.request({ action: 'view', view });
  await assert.rejects(docs.request({ action: 'view', view: { ...view, sort: 'arbitrary' } }));
  db.close(); const reopened = new WorkspaceDatabase(join(root, 'workspace.sqlite')), next = new DocumentRepository(reopened);
  assert.deepEqual(next.snapshot().view, view);
  assert.equal(next.get(id).name, '共通マニュアル'); assert.equal(next.snapshot().uses.find(use => use.documentId === id && use.contextId === a.id)!.group, '手順・準備');
  await next.request({ action: 'remove', id, revision: next.get(id).revision, linkCount: 3 });
  assert.equal(next.snapshot().uses.filter(use => use.documentId === id).length, 0); assert.deepEqual(readFileSync(original), before); assert.equal(readFileSync(other, 'utf8'), 'other original');
  reopened.close();
});
test('offline reference errors preserve metadata, do not serialize local editing, and corrections reuse the record', async () => {
  const { db, docs, a } = setup();
  const batch = await docs.request({ action: 'register', entries: [{ reference: '\\\\unavailable.invalid\\share\\manual.pdf', kind: 'file' }], context: null }) as DocumentBatch;
  let requested = '';
  const actions = new DocumentActions(docs, { pick: async () => [], openPath: async reference => { requested = reference; return 'Network location not found'; }, openExternal: async () => {} });
  const failure = await actions.request({ action: 'open', id: batch.registered[0] }); assert.equal(failure.ok, false);
  if (!failure.ok) assert.match(failure.error.message, /unavailable.invalid.*[\s\S]*Network location not found/);
  assert.equal(requested, '\\\\unavailable.invalid\\share\\manual.pdf');
  const page = db.item(a.id); assert.ok(db.setArchived({ kind: 'item', id: a.id, archived: true, baseRevision: page.revision }).item!.archived);
  await assert.rejects(docs.request({ action: 'attach', id: batch.registered[0], context: { kind: 'item', id: a.id } }));
  const doc = docs.get(batch.registered[0]!);
  await docs.request({ action: 'edit', id: doc.id, revision: doc.revision, name: '', reference: 'https://example.com/Manual', description: '修正', kind: 'url' });
  assert.equal(docs.get(doc.id).kind, 'url'); assert.equal((await actions.request({ action: 'open', id: doc.id })).ok, true);
  assert.equal((await actions.request({ action: 'open', id: doc.id, command: 'bad' })).ok, false);
  db.db.exec('PRAGMA query_only=ON');
  const failed = await docs.request({ action: 'register', entries: [{ reference: 'C:\\missing\\file.txt', kind: 'file' }], context: null }) as DocumentBatch;
  assert.equal(failed.failed.length, 1); assert.equal(failed.registered.length, 0); db.db.exec('PRAGMA query_only=OFF'); db.close();
});
